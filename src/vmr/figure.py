"""Render results/figure.png and results/summary.md from results/metrics.json and the audit."""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402


def short(model: str) -> str:
    return model.split("/", 1)[1]


def pct(value) -> str:
    return f"{100 * value:.1f}%"


def interval_text(pair) -> str:
    return f"{100 * pair[0]:.1f}-{100 * pair[1]:.1f}%" if pair else ""


def figure(metrics: dict, path: Path) -> None:
    models, families = metrics["models"], metrics["families"]
    acc = np.array([[metrics["family_by_model"][f"{f}|{m}"]["accuracy"] for m in models] for f in families])
    share = np.array([[metrics["router_final_third_pick_share"][f][m] for m in models] for f in families])
    fig, axes = plt.subplots(1, 2, figsize=(11, 3.9), constrained_layout=True)
    panels = [(axes[0], acc, "Measured accuracy (strict, 1 sample)"),
              (axes[1], share, "Router's picks, last third of each family")]
    for ax, data, title in panels:
        ax.imshow(data, cmap="Blues", vmin=0, vmax=1, aspect="auto")
        ax.set_xticks(range(len(models)), [short(m) for m in models], fontsize=9)
        ax.set_yticks(range(len(families)), families)
        ax.set_title(title, fontsize=11, loc="left")
        for i in range(len(families)):
            for j in range(len(models)):
                n = metrics["family_by_model"][f"{families[i]}|{models[j]}"]
                label = f"{n['correct']}/{n['n']}" if data is acc else pct(data[i, j])
                ax.text(j, i, label, ha="center", va="center", fontsize=10,
                        color="white" if data[i, j] > 0.6 else "black")
        ax.tick_params(length=0)
        for side in ax.spines.values():
            side.set_visible(False)
    source = metrics["source"]
    note = "MOCK DATA - NOT A RESULT" if source != "openrouter" else (
        f"{metrics['n_problems']} SymPy-checked problems, one response per model; "
        f"router = Thompson sampling per family, {metrics['runs']} shuffled replays")
    fig.suptitle(note, fontsize=9, color="red" if source != "openrouter" else "#444", x=0.01, ha="left")
    fig.savefig(path, dpi=150, metadata={"Software": None})
    plt.close(fig)


def summary(metrics: dict, audit: dict) -> str:
    models, families = metrics["models"], metrics["families"]
    out = ["<!-- Generated by `python -m vmr.figure` from results/metrics.json and results/verifier_audit.json. -->", ""]
    out += ["### Accuracy by family (correct / 40, strict scoring; mean $ per problem in brackets)", "",
            "| family | " + " | ".join(short(m) for m in models) + " | router's late picks |",
            "|---|" + "---|" * (len(models) + 1)]
    for f in families:
        cells = [f"{metrics['family_by_model'][f'{f}|{m}']['correct']}/{metrics['family_by_model'][f'{f}|{m}']['n']} "
                 f"(${metrics['family_by_model'][f'{f}|{m}']['mean_cost_usd']:.5f})" for m in models]
        late = metrics["router_final_third_pick_share"][f]
        top = max(late, key=late.get)
        out.append(f"| {f} | " + " | ".join(cells) + f" | {short(top)} {pct(late[top])} |")
    out += ["", "### Routing policies (accuracy and cost over the 120 problems)", "",
            "| policy | accuracy | problem-bootstrap 95% | order 95% | mean $ / problem |", "|---|---|---|---|---|"]
    for name, p in metrics["policies"].items():
        out.append(f"| {name} | {pct(p['accuracy'])} | {interval_text(p.get('accuracy_problem_interval'))} | "
                   f"{interval_text(p.get('accuracy_order_interval'))} | {p['mean_cost_usd']:.5f} |")
    out += ["", "### Cost-aware Thompson sampling (score = sampled accuracy - mean cost / V)", "",
            "| V ($ per correct answer) | accuracy | mean $ / problem |", "|---|---|---|"]
    for row in metrics["cost_aware_thompson"]:
        out.append(f"| {row['value_per_correct_usd']} | {pct(row['accuracy'])} | {row['mean_cost_usd']:.5f} |")
    out += ["", "### Simulated verifier noise (real responses, rewards flipped at the given rate)", "",
            "| false accept = false reject rate | router's true accuracy |", "|---|---|"]
    for row in metrics["reward_noise_simulation"]:
        out.append(f"| {row['false_accept_and_false_reject_rate']} | {pct(row['true_accuracy'])} |")
    out += ["", "### Verdicts by model", "", "| model | " + " | ".join(
        ["correct", "wrong", "unparseable", "no_answer", "truncated", "inconclusive"]) + " | lenient accuracy | total $ |",
            "|---|" + "---|" * 8]
    for m in models:
        o = metrics["models_overall"][m]
        counts = [str(o["status_counts"].get(s, 0)) for s in ["correct", "wrong", "unparseable", "no_answer", "truncated", "inconclusive"]]
        out.append(f"| {short(m)} | " + " | ".join(counts) + f" | {pct(o['lenient_accuracy'])} | {o['total_cost_usd']:.4f} |")
    s = metrics["specialization"]
    out += ["", "### Specialization test (rule fixed before the main run)", "",
            f"- Best model overall: {short(s['overall_best_model'])}. Best per family: "
            + ", ".join(f"{f} = {short(v['best_model'])}" for f, v in s["per_family"].items()) + ".",
            f"- Headroom H (per-family best minus best single, in hindsight): {pct(s['headroom_H'])}, permutation p = {s['headroom_permutation_p']}.",
            f"- Split-half out-of-sample gain: mean {pct(s['split_half_gain_mean'])} (2.5-97.5 percentiles over splits {interval_text(s['split_half_gain_2.5_97.5_percentiles'])}).",
            f"- Rule: {', '.join(f'{k} = {v}' for k, v in s['rule'].items())}. **Specialized: {s['specialized']}.**"]
    fa, fr = audit["summary"]["false_accept"]["all"], audit["summary"]["false_reject"]["all"]
    out += ["", "### Verifier audit (injected answers)", "",
            f"- False accepts: {fa['errors']}/{fa['trials']} deliberately wrong answers accepted (Wilson 95% upper bound {pct(fa['wilson95'][1])}).",
            f"- False rejects: {fr['errors']}/{fr['trials']} equivalent rewrites not accepted (Wilson 95% upper bound {pct(fr['wilson95'][1])}).", ""]
    return "\n".join(out)


def main() -> None:
    metrics = json.loads(Path("results/metrics.json").read_text())
    audit = json.loads(Path("results/verifier_audit.json").read_text())
    figure(metrics, Path("results/figure.png"))
    Path("results/summary.md").write_text(summary(metrics, audit))
    print("results/figure.png and results/summary.md written")


if __name__ == "__main__":
    main()
